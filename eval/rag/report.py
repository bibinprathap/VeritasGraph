"""JSON metrics -> markdown tables (Table III / IV / V) with mean +/- std.

Guards the plan's principle #1 ("no number without a file"): a table cell is
only emitted if it is backed by a committed JSON in ``results/rag/metrics/``.
If a (task, system) cell has no backing JSON, the cell is rendered as
``n/a (missing <file>)`` — never a fabricated number.

CLI:

    python -m eval.rag.report                 # all tables
    python -m eval.rag.report --task hotpotqa # just Table IV
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from .config import load_config

SYSTEMS = ("naive", "msrag", "veritasgraph")
SYSTEM_LABELS = {
    "naive": "Naive RAG",
    "msrag": "MSRAG (GraphRAG)",
    "veritasgraph": "VeritasGraph (ours)",
}

# Table IV — HotpotQA QA metrics
QA_METRICS = ("em", "f1")
# Table V — Attribution metrics
CIT_METRICS = ("cit_p", "cit_r", "cit_f1", "cit_faith")
# Table III — QFS judge metrics
QFS_METRICS = ("comprehensiveness", "diversity")

TASK_TABLES = {
    "hotpotqa": ("table_iv.md", QA_METRICS + CIT_METRICS),
    "behindthetech": ("table_iii.md", QFS_METRICS),
}

METRIC_LABELS = {
    "em": "EM",
    "f1": "Token-F1",
    "cit_p": "Cit. Precision",
    "cit_r": "Cit. Recall",
    "cit_f1": "Cit. F1",
    "cit_faith": "Cit. Faithfulness",
    "comprehensiveness": "Comprehensiveness",
    "diversity": "Diversity",
}


# --------------------------------------------------------------------------- #
# Loading
# --------------------------------------------------------------------------- #
def load_metrics(metrics_dir: Path) -> Dict[Tuple[str, str, int], Dict[str, Any]]:
    """Load every committed metrics JSON keyed by (task, system, seed)."""
    out: Dict[Tuple[str, str, int], Dict[str, Any]] = {}
    if not metrics_dir.is_dir():
        return out
    for path in sorted(metrics_dir.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        task = data.get("task")
        system = data.get("system")
        seed = data.get("seed")
        if task is None or system is None or seed is None:
            continue
        out[(str(task), str(system), int(seed))] = data
    return out


def _mean_over_seeds(
    blobs: Sequence[Dict[str, Any]], metric: str
) -> Optional[Tuple[float, float]]:
    """Mean +/- std of a metric across seed-level means. None if absent."""
    values: List[float] = []
    for blob in blobs:
        m = blob.get("metrics", {}).get(metric)
        if m is None:
            continue
        values.append(float(m["mean"]))
    if not values:
        return None
    mean = sum(values) / len(values)
    if len(values) > 1:
        var = sum((v - mean) ** 2 for v in values) / (len(values) - 1)
        std = var ** 0.5
    else:
        std = 0.0
    return mean, std


# --------------------------------------------------------------------------- #
# Table rendering
# --------------------------------------------------------------------------- #
def render_table(
    task: str,
    loaded: Dict[Tuple[str, str, int], Dict[str, Any]],
    metrics_dir: Path,
    *,
    bold_best: bool = True,
) -> str:
    """Render one markdown table for a task; missing cells are explicit."""
    filename, metric_keys = TASK_TABLES[task]
    systems_present = sorted({system for (t, system, _) in loaded if t == task})

    lines: List[str] = []
    header = ["System"] + [METRIC_LABELS.get(m, m) for m in metric_keys]
    lines.append(f"<!-- generated by eval.rag.report from {metrics_dir} -->")
    lines.append("| " + " | ".join(header) + " |")
    lines.append("|" + "---|" * len(header))

    # Which systems do we render? Always all known systems, so gaps are visible.
    render_systems = sorted(set(systems_present) | set(SYSTEMS))

    # Track best mean per metric for bolding (only over present cells).
    best: Dict[str, float] = {}
    cell_values: Dict[str, Dict[str, Optional[Tuple[float, float]]]] = {}
    for system in render_systems:
        blobs = [loaded[k] for k in loaded if k[0] == task and k[1] == system]
        row: Dict[str, Optional[Tuple[float, float]]] = {}
        for m in metric_keys:
            agg = _mean_over_seeds(blobs, m)
            row[m] = agg
            if agg is not None and (m not in best or agg[0] > best[m]):
                best[m] = agg[0]
        cell_values[system] = row

    for system in render_systems:
        row = cell_values[system]
        cells = [SYSTEM_LABELS.get(system, system)]
        for m in metric_keys:
            agg = row[m]
            if agg is None:
                expected = metrics_dir / f"{task}__{system}__seed*.json"
                cells.append(f"n/a (missing `{expected.name}`)")
                continue
            mean, std = agg
            text = f"{mean:.3f} ± {std:.3f}"
            if bold_best and len(render_systems) > 1 and best.get(m) == mean:
                text = f"**{text}**"
            cells.append(text)
        lines.append("| " + " | ".join(cells) + " |")

    lines.append("")
    lines.append(f"_n per cell: see backing JSONs in `{metrics_dir}`; "
                 "every value traces to a committed file (no hypothesised numbers)._")
    return "\n".join(lines) + "\n"


def generate_all(
    metrics_dir: Path, tables_dir: Path, tasks: Optional[Sequence[str]] = None
) -> List[Path]:
    """Generate the markdown tables; returns the files written."""
    loaded = load_metrics(metrics_dir)
    tables_dir.mkdir(parents=True, exist_ok=True)
    written: List[Path] = []
    for task in (tasks or list(TASK_TABLES)):
        if task not in TASK_TABLES:
            continue
        md = render_table(task, loaded, metrics_dir)
        out = tables_dir / TASK_TABLES[task][0]
        out.write_text(md, encoding="utf-8")
        written.append(out)
    return written


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(prog="eval.rag.report")
    parser.add_argument("--task", default="all",
                        choices=["all", *TASK_TABLES])
    parser.add_argument("--config", default=None)
    args = parser.parse_args(argv)

    cfg = load_config(args.config)
    metrics_dir = Path(cfg.output.metrics_dir)
    tables_dir = Path(cfg.output.tables_dir)

    tasks = None if args.task == "all" else [args.task]
    written = generate_all(metrics_dir, tables_dir, tasks)
    for path in written:
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
